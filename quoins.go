package main

// Shared street quoins (multiplayer phase 4). As in the original, a street's
// quoins are the same for everyone on it: the first Glitch to touch a spawned
// one gets it, it vanishes for everyone, and it comes back after its class's
// respawn_time; Glitches standing near the grab get a shard of it.
//
// Source: GameServerJS items/quoin.js onPlayerCollision (156-310: first
// toucher wins, spawned = 0, buildState visible:false, onRespawn after
// respawn_time), distributeQuoinShards (83-154) and the class table in
// onPropsChanged (318-662).
//
// The server owns which quoins a street has (data/quoins.json,
// generated by tools/build-realtime-quoins.mjs from the same street data,
// population and planner the game uses), whether each is spawned, its
// respawn timer, the rolled benefit of a random quoin and every shard. A
// claim is checked against the claimer's last known position. The claimer's
// own multiplier, the daily quoin limit (pc.stats.quoins_today, quoin.js
// 159) and applying the reward stay with the claimer's client, as in solo.
// Currants are the ledger's, so a currants grab and each currants shard are
// also credited to the site (credits.go): the benefit times the multiplier
// the claimer reported (quoin_status, capped at the source's 100), for the
// first quoinCreditDaily grabs of a game day.
// Personal quoins (Qurazy, quest and demo quoins, private instances) never
// come here.
//
// Client to server:
//
//	{"t":"quoin_sync","street":"GA5…"}                after the street answer to a join: the quoins there
//	{"t":"quoin_claim","street":"GA5…","i":3}         touched natural quoin 3 of this street
//	{"t":"quoin_status","afk":false,"following":false,"mult":1}   for shard eligibility
//
// Server to client:
//
//	{"t":"quoins","street":"GA5…","shared":true,"quoins":[{"i":0,"x":0,"y":0,"type":"xp","class":"small random xp"}],"gone":[3]}
//	    the answer to quoin_sync; shared:false (no quoins key) for a street the server has no quoins for
//	{"t":"quoin_got","street":"GA5…","i":3,"type":"xp","amount":4,"x":0,"y":0,"crowd":2,"shards":[Shard…]}
//	    to the claimer: amount is the benefit before the claimer's multiplier (quoin.js 161-174)
//	{"t":"quoin_taken","street":"GA5…","i":3,"id":7,"name":"Ada","type":"xp","amount":4,"x":0,"y":0,"crowd":2,"shards":[Shard…]}
//	    to everyone else on the street (quoin.js 239-247 quoin_got announcement)
//	{"t":"quoin_refused","street":"GA5…","i":3,"why":"gone|far|street|unknown|slow"}
//	{"t":"quoin_back","street":"GA5…","i":3}          respawned (quoin.js 305, onRespawn 664)
//
// Shard: {"id":8,"x":0,"y":0,"amount":2,"pct":0.31}: a receiver, where they
// stood, and what they get with their own multiplier (quoin.js 107-118).

import (
	_ "embed"
	"encoding/json"
	"log"
	"math"
	"math/rand/v2"
	"sort"
	"time"
)

//go:embed data/quoins.json
var quoinsJSON []byte

const (
	// game.js collects a quoin whose centre is within 44 px of the avatar's
	// middle (feet minus 28). Moves arrive at most every 100 ms and a claim
	// can beat the last one, so the server allows some travel on top.
	quoinTouch      = 44.0
	quoinTouchSlack = 120.0
	quoinFeetLift   = 28.0

	// items/quoin.js 86 and 107-111.
	shardRadius = 300.0
	shardNear   = 25.0
	shardFall   = 275.0
	shardTop    = 0.50
	shardFloor  = 0.05

	claimsPerSec = 8
	statusPerSec = 4
	maxQuoinMult = 100.0
)

// quoinShardTypes: quoin.js 84, only these share.
var quoinShardTypes = map[string]bool{"xp": true, "mood": true, "energy": true, "currants": true}

type quoinSpot struct {
	X, Y        float64
	Type, Class string
}

type quoinClass struct {
	Type    string `json:"type"`
	Respawn int    `json:"respawn"`
	Benefit *int   `json:"benefit"`
	Floor   int    `json:"floor"`
	Ceil    int    `json:"ceil"`
}

type quoinData struct {
	Types   map[string]int        `json:"types"`
	Classes map[string]quoinClass `json:"classes"`
	streets map[string][]quoinSpot
}

func parseQuoinData(b []byte) (*quoinData, error) {
	var raw struct {
		quoinData
		Streets map[string][][4]json.RawMessage `json:"streets"`
	}
	if err := json.Unmarshal(b, &raw); err != nil {
		return nil, err
	}
	d := raw.quoinData
	d.streets = make(map[string][]quoinSpot, len(raw.Streets))
	for tsid, rows := range raw.Streets {
		spots := make([]quoinSpot, 0, len(rows))
		for _, r := range rows {
			var s quoinSpot
			if json.Unmarshal(r[0], &s.X) != nil || json.Unmarshal(r[1], &s.Y) != nil || json.Unmarshal(r[2], &s.Type) != nil || json.Unmarshal(r[3], &s.Class) != nil {
				continue
			}
			spots = append(spots, s)
		}
		d.streets[tsid] = spots
	}
	return &d, nil
}

// QuoinShard is one Glitch's share of someone's grab.
type QuoinShard struct {
	ID     int64   `json:"id"`
	X      float64 `json:"x"`
	Y      float64 `json:"y"`
	Amount int     `json:"amount"`
	Pct    float64 `json:"pct"`
}

type quoinStatus struct {
	afk, following bool
	mult           float64

	claimWindow  time.Time
	claims       int
	statusWindow time.Time
	statuses     int
}

type quoinsModule struct {
	h    *Hub
	data *quoinData
	// gone[street][i]: unspawned until its respawn timer runs.
	gone   map[string]map[int]func() bool
	status map[int64]*quoinStatus
	// grabs[id]: natural quoins a player grabbed this game day, for the credits' daily count.
	grabs map[int64]quoinDay
	// randInt is the source's randInt (common.js 691: lo..hi, both included).
	randInt func(lo, hi int) int

	// The state file (quoins_persist.go): when each gone quoin comes back, and the day's grabs.
	path    string
	due     map[string]map[int]time.Time
	saveAt  bool
	resumed bool
}

func init() { modules = append(modules, newQuoins) }

func newQuoins(h *Hub) Module {
	d, err := parseQuoinData(quoinsJSON)
	if err != nil {
		panic("realtime: data/quoins.json: " + err.Error())
	}
	return newQuoinsWith(h, d)
}

func newQuoinsWith(h *Hub, d *quoinData) *quoinsModule {
	m := &quoinsModule{
		h:       h,
		data:    d,
		gone:    map[string]map[int]func() bool{},
		status:  map[int64]*quoinStatus{},
		grabs:   map[int64]quoinDay{},
		randInt: func(lo, hi int) int { return lo + rand.IntN(hi-lo+1) },
		due:     map[string]map[int]time.Time{},
		resumed: true,
	}
	if m.path = statePath(quoinsFileForTest, quoinsFileFlag, "realtime-quoins.json"); m.path != "" {
		if err := m.load(); err != nil {
			log.Printf("quoins %s: %v (quoins are kept in memory only)", m.path, err)
			m.path = ""
		}
	}
	return m
}

func (m *quoinsModule) Register(r *Registry) {
	r.Handle("quoin_claim", m.claim)
	r.Handle("quoin_status", m.setStatus)
	r.OnConnect(func(cl *Client) { m.resume(); m.status[cl.ID()] = &quoinStatus{mult: 1} })
	r.OnDisconnect(func(cl *Client) { delete(m.status, cl.ID()) })
	r.Handle("quoin_sync", m.syncReq)
	r.OnShutdown(func() { m.save() })
}

func (m *quoinsModule) statusOf(cl *Client) *quoinStatus {
	st := m.status[cl.ID()]
	if st == nil {
		st = &quoinStatus{mult: 1}
		m.status[cl.ID()] = st
	}
	return st
}

// syncReq answers quoin_sync for the street the asker stands on (a stale
// street, from before another join, gets no answer: that join asks again).
func (m *quoinsModule) syncReq(cl *Client, frame json.RawMessage) {
	var msg struct {
		Street string `json:"street"`
	}
	if json.Unmarshal(frame, &msg) != nil || cl.Street() == "" || msg.Street != cl.Street() {
		return
	}
	st := m.statusOf(cl)
	now := m.h.Now()
	if now.Sub(st.statusWindow) >= time.Second {
		st.statusWindow, st.statuses = now, 0
	}
	st.statuses++
	if st.statuses > statusPerSec {
		return
	}
	m.sync(cl)
}

// sync tells a Glitch on a street its quoins and which are gone.
func (m *quoinsModule) sync(cl *Client) {
	street := cl.Street()
	spots := m.spotsOf(street)
	if len(spots) == 0 {
		m.h.SendLocked(cl, map[string]any{"t": "quoins", "street": street, "shared": false})
		return
	}
	list := make([]map[string]any, len(spots))
	for i, s := range spots {
		list[i] = map[string]any{"i": i, "x": s.X, "y": s.Y, "type": s.Type, "class": s.Class}
	}
	gone := make([]int, 0, len(m.gone[street]))
	for i := range m.gone[street] {
		gone = append(gone, i)
	}
	sort.Ints(gone)
	m.h.SendLocked(cl, map[string]any{"t": "quoins", "street": street, "shared": true, "quoins": list, "gone": gone})
}

// spotsOf is a street's natural quoins. A Party Space's instance (PARTY_<id>,
// party_spaces.go) has its template's, shared by the party in it.
func (m *quoinsModule) spotsOf(street string) []quoinSpot {
	if spots, ok := m.data.streets[street]; ok {
		return spots
	}
	if fn, ok := m.h.ProvidedLocked("party.spaceStreet").(func(string) string); ok {
		if t := fn(street); t != "" {
			return m.data.streets[t]
		}
	}
	return nil
}

func (m *quoinsModule) setStatus(cl *Client, frame json.RawMessage) {
	var msg struct {
		AFK       bool     `json:"afk"`
		Following bool     `json:"following"`
		Mult      *float64 `json:"mult"`
	}
	if json.Unmarshal(frame, &msg) != nil {
		return
	}
	st := m.statusOf(cl)
	now := m.h.Now()
	if now.Sub(st.statusWindow) >= time.Second {
		st.statusWindow, st.statuses = now, 0
	}
	st.statuses++
	if st.statuses > statusPerSec {
		return
	}
	st.afk, st.following = msg.AFK, msg.Following
	st.mult = cleanMult(msg.Mult)
}

// cleanMult keeps a reported quoin multiplier to 1..100 (js/quoins.js normalizeQuoinState).
func cleanMult(v *float64) float64 {
	if v == nil || math.IsNaN(*v) || math.IsInf(*v, 0) {
		return 1
	}
	return math.Max(1, math.Min(maxQuoinMult, *v))
}

func (m *quoinsModule) refuse(cl *Client, street string, i int, why string) {
	m.h.SendLocked(cl, map[string]any{"t": "quoin_refused", "street": street, "i": i, "why": why})
}

func (m *quoinsModule) claim(cl *Client, frame json.RawMessage) {
	var msg struct {
		Street string `json:"street"`
		I      *int   `json:"i"`
	}
	if json.Unmarshal(frame, &msg) != nil || msg.I == nil || !streetRe.MatchString(msg.Street) {
		m.h.ErrorLocked(cl, "bad_quoin", "That quoin claim did not make sense.")
		return
	}
	i := *msg.I
	st := m.statusOf(cl)
	now := m.h.Now()
	if now.Sub(st.claimWindow) >= time.Second {
		st.claimWindow, st.claims = now, 0
	}
	st.claims++
	if st.claims > claimsPerSec {
		m.refuse(cl, msg.Street, i, "slow")
		return
	}
	street := cl.Street()
	if street == "" || msg.Street != street {
		m.refuse(cl, msg.Street, i, "street")
		return
	}
	spots := m.spotsOf(street)
	if i < 0 || i >= len(spots) {
		m.refuse(cl, street, i, "unknown")
		return
	}
	// quoin.js 157: if (!this.spawned) return.
	if _, gone := m.gone[street][i]; gone {
		m.refuse(cl, street, i, "gone")
		return
	}
	spot := spots[i]
	px, py := cl.Pos()
	if math.Hypot(spot.X-px, spot.Y-(py-quoinFeetLift)) > quoinTouch+quoinTouchSlack {
		m.refuse(cl, street, i, "far")
		return
	}
	amount := m.benefit(spot)
	shards, crowd := m.shards(cl, street, spot.Type, amount)

	// quoin.js 236-237 and 305: unspawn for everyone, respawn after respawn_time.
	if m.gone[street] == nil {
		m.gone[street] = map[int]func() bool{}
	}
	respawn := time.Duration(m.respawnSec(spot)) * time.Second
	m.gone[street][i] = m.h.After(respawn, func() { m.respawn(street, i) })
	m.markDue(street, i, m.h.Now().Add(respawn))

	m.h.SendLocked(cl, map[string]any{"t": "quoin_got", "street": street, "i": i, "type": spot.Type, "amount": amount, "x": spot.X, "y": spot.Y, "crowd": crowd, "shards": shards})
	m.h.BroadcastStreetLocked(street, map[string]any{"t": "quoin_taken", "street": street, "i": i, "id": cl.ID(), "name": cl.Name(), "type": spot.Type, "amount": amount, "x": spot.X, "y": spot.Y, "crowd": crowd, "shards": shards}, cl.ID())
	m.credit(cl, spot.Type, amount, st.mult, shards)
	m.saveSoon()
}

// quoinDay counts one player's grabs in one game day (objects.go's day).
type quoinDay struct {
	day int64
	n   int
}

// credit tells the site's ledger the currants a grab gave (credits.go): the
// grabber's round(amount * multiplier) (quoin.js 171-174), while this game
// day's grabs, every type counted as quoins_today counts them, are within
// quoinCreditDaily; and every currants shard as sent.
func (m *quoinsModule) credit(cl *Client, typ string, amount int, mult float64, shards []QuoinShard) {
	day := int64(math.Floor(float64(m.h.Now().UnixMilli()-gameEpochMs) / gameDayMs))
	g := m.grabs[cl.ID()]
	if g.day != day {
		g = quoinDay{day: day}
	}
	g.n++
	m.grabs[cl.ID()] = g
	if typ != "currants" {
		return
	}
	if g.n <= quoinCreditDaily {
		creditLocked(m.h, cl.ID(), "quoin", tradeGoods{Currants: int64(math.Round(float64(amount) * mult))})
	}
	for _, s := range shards {
		creditLocked(m.h, s.ID, "shard", tradeGoods{Currants: int64(s.Amount)})
	}
}

func (m *quoinsModule) respawn(street string, i int) {
	if _, ok := m.gone[street][i]; !ok {
		return
	}
	delete(m.gone[street], i)
	if len(m.gone[street]) == 0 {
		delete(m.gone, street)
	}
	m.markDue(street, i, time.Time{})
	m.saveSoon()
	m.h.BroadcastStreetLocked(street, map[string]any{"t": "quoin_back", "street": street, "i": i}, 0)
}

// respawnSec is the spot's class respawn_time (quoin.js 318-662), an hour for a class the table lacks.
func (m *quoinsModule) respawnSec(s quoinSpot) int {
	if c, ok := m.data.Classes[s.Class]; ok && c.Respawn > 0 {
		return c.Respawn
	}
	return 3600
}

// benefit is what one grab gives before the claimer's multiplier (quoin.js
// 161-166): the class's benefit, or randInt(floor, ceil) for a random class;
// a class of another type (mystery spots carry the iMG pair) gives the
// quoin type's own base amount (js/quoins.js quoinClassAmount, collectQuoin).
func (m *quoinsModule) benefit(s quoinSpot) int {
	c, ok := m.data.Classes[s.Class]
	if !ok || (c.Type != "" && c.Type != s.Type) {
		return m.data.Types[s.Type]
	}
	if c.Benefit != nil {
		return *c.Benefit
	}
	if c.Ceil < c.Floor {
		return c.Floor
	}
	return m.randInt(c.Floor, c.Ceil)
}

// shardPct is quoin.js 108-111: half within 25 px, then a straight fall to 5% at 300 px.
func shardPct(dist float64) float64 {
	if dist <= shardNear {
		return shardTop
	}
	return math.Max(shardTop-shardTop*((dist-shardNear)/shardFall), shardFloor)
}

// shards is distributeQuoinShards (quoin.js 83-154): every other active Glitch
// within 300 px of the grabber, nearest first, who is not following anyone and
// not AFK, gets max(round(amount * their multiplier * share), 1). crowd counts
// everyone in the radius, the grabber included (the QUOIN_SHARD_<n> sound, 94).
func (m *quoinsModule) shards(cl *Client, street, typ string, amount int) ([]QuoinShard, int) {
	out := []QuoinShard{}
	if !quoinShardTypes[typ] {
		return out, 0
	}
	gx, gy := cl.Pos()
	type near struct {
		o    *Client
		dist float64
	}
	var in []near
	for _, o := range m.h.StreetLocked(street) {
		if o.ID() == cl.ID() || !o.Online() {
			continue
		}
		ox, oy := o.Pos()
		if d := math.Hypot(ox-gx, oy-gy); d <= shardRadius {
			in = append(in, near{o, d})
		}
	}
	sort.Slice(in, func(a, b int) bool {
		if in[a].dist != in[b].dist {
			return in[a].dist < in[b].dist
		}
		return in[a].o.ID() < in[b].o.ID()
	})
	for _, n := range in {
		st := m.statusOf(n.o)
		if st.following || st.afk {
			continue
		}
		pct := shardPct(n.dist)
		ox, oy := n.o.Pos()
		out = append(out, QuoinShard{
			ID:     n.o.ID(),
			X:      ox,
			Y:      oy,
			Amount: int(math.Max(math.Round(float64(amount)*st.mult*pct), 1)),
			Pct:    math.Round(pct*1000) / 1000,
		})
	}
	return out, len(in) + 1
}
